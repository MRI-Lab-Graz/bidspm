(function () {
  'use strict';

  // Tracks, for a chain of transformer Instructions, what string values each
  // column will hold once the pipeline runs — so the main analysis GUI can offer
  // the same per-level (e.g. "trial_group.single_W") Model.X suggestions that the
  // standalone Transformer Builder's "Generated Columns" pool already shows.
  //
  // This mirrors every op handled by the transformer (Filter, Concatenate, Factor,
  // Replace, Copy, Assign, ...). Keeping this logic in one place avoids the domain
  // tracking silently falling out of sync between the pages that need it.

  function normalizeStringArray(value) {
    if (Array.isArray(value)) return value.map((item) => String(item).trim()).filter(Boolean);
    if (value === undefined || value === null || typeof value === 'object') return [];
    const normalized = String(value).trim();
    return normalized ? [normalized] : [];
  }

  function normalizeDomainValues(values) {
    return normalizeStringArray(values).filter((v) => v && v !== 'n/a');
  }

  function shouldOfferLevelSuggestions(values) {
    const domain = normalizeDomainValues(values);
    if (!domain.length) return false;
    if (domain.every((v) => v === '0' || v === '1')) return false;
    return domain.some((v) => Number.isNaN(Number(v)));
  }

  function buildCombinations(levelSets, index = 0, parts = [], names = []) {
    if (index >= levelSets.length) {
      if (parts.length) names.push(parts.join('_'));
      return names;
    }
    levelSets[index].forEach((level) => buildCombinations(levelSets, index + 1, [...parts, level], names));
    return names;
  }

  function normalizeFilterLiteral(value) {
    const literal = String(value || '').trim();
    if (!literal) return '';
    if ((literal.startsWith('\'') && literal.endsWith('\'')) || (literal.startsWith('"') && literal.endsWith('"'))) {
      return literal.slice(1, -1).trim();
    }
    return literal.replace(/^\(+|\)+$/g, '').trim();
  }

  // Supports both:
  //  - a single anchored regex alternation, e.g. `col==^(a|b|c)$` — the format
  //    generated by the Filter step's multi-value pills, and the only compound
  //    form the backend (bids.transformers Filter/get_query) actually executes.
  //  - the legacy "col == 'a' | col == 'b'" pipe-of-clauses form, kept for queries
  //    written by hand before the multi-select pills existed.
  function inferFilterDomain(query, inputColumn, inputValues) {
    const normalizedInput = String(inputColumn || '').trim();
    const domain = normalizeDomainValues(inputValues);
    const normalizedQuery = String(query || '').trim();
    if (!normalizedInput || !normalizedQuery) return domain;

    const matched = new Set();

    const altMatch = normalizedQuery.match(/^(.+?)\s*==\s*\^\((.*)\)\$$/);
    if (altMatch && String(altMatch[1] || '').trim() === normalizedInput) {
      altMatch[2].split('|').map((v) => v.trim()).filter(Boolean).forEach((v) => matched.add(v));
      const filtered = domain.filter((v) => matched.has(String(v)));
      return filtered.length ? filtered : Array.from(matched);
    }

    let sawInputEquality = false;
    normalizedQuery.split('|').map((part) => part.trim()).filter(Boolean).forEach((part) => {
      const clause = part.replace(/^\(+|\)+$/g, '').trim();
      const match = clause.match(/^(.+?)\s*==\s*(.+)$/);
      if (!match) return;

      const left = String(match[1] || '').trim();
      if (left !== normalizedInput) return;

      sawInputEquality = true;
      const literal = normalizeFilterLiteral(match[2]);
      if (literal) matched.add(literal);
    });

    if (!sawInputEquality) return domain;
    const filtered = domain.filter((v) => matched.has(String(v)));
    return filtered.length ? filtered : Array.from(matched);
  }

  function applyReplacements(value, replacements) {
    let nextValue = String(value ?? '').trim();
    replacements.forEach((rule) => {
      const key = String(rule?.key || '').trim();
      if (!key) return;

      const replacement = String(rule?.value ?? '').trim();
      if (nextValue === key) {
        nextValue = replacement;
        return;
      }

      try {
        const regex = new RegExp(key);
        if (regex.test(nextValue)) nextValue = nextValue.replace(regex, replacement);
      } catch (e) {
        // Ignore invalid regex patterns while still applying literal-match replacements above.
      }
    });
    return nextValue;
  }

  // Mutates domainMap in place, propagating the value domain for this instruction's
  // output column(s) from its input column(s).
  function applyDomainPropagation(domainMap, instruction) {
    const opName = String(instruction?.Name || '').trim();
    if (!opName) return;

    const inputColumns = normalizeStringArray(instruction.Input);
    const outputColumns = normalizeStringArray(instruction.Output);
    const inputColumn = inputColumns[0] || '';
    const targetColumn = outputColumns[0] || inputColumn;

    switch (opName) {
      case 'Filter': {
        if (!targetColumn) return;
        domainMap[targetColumn] = inferFilterDomain(instruction.Query, inputColumn, domainMap[inputColumn] || []);
        return;
      }
      case 'Concatenate': {
        const outputName = outputColumns[0];
        if (!outputName || !inputColumns.length) return;
        const levelSets = inputColumns.map((col) => domainMap[col] || []);
        if (levelSets.some((levels) => !levels.length)) return;
        domainMap[outputName] = normalizeDomainValues(buildCombinations(levelSets));
        return;
      }
      case 'Factor': {
        if (!inputColumns.length) return;
        const levelSets = inputColumns.map((col) => domainMap[col] || []);
        if (levelSets.some((levels) => !levels.length)) return;
        const factorColumns = [];
        const build = (index, parts) => {
          if (index >= inputColumns.length) {
            factorColumns.push(parts.join('_'));
            return;
          }
          levelSets[index].forEach((level) => build(index + 1, [...parts, inputColumns[index], level]));
        };
        build(0, []);
        factorColumns.forEach((name) => { domainMap[name] = ['0', '1']; });
        return;
      }
      case 'Replace': {
        if (!targetColumn) return;
        const replacements = Array.isArray(instruction.Replace) ? instruction.Replace : [];
        domainMap[targetColumn] = normalizeDomainValues(
          (domainMap[inputColumn] || []).map((v) => applyReplacements(v, replacements))
        );
        return;
      }
      case 'Copy': {
        if (!inputColumns.length || !outputColumns.length) return;
        outputColumns.forEach((outputName, index) => {
          const sourceName = inputColumns[index] || inputColumns[inputColumns.length - 1];
          if (!outputName || !sourceName) return;
          domainMap[outputName] = [...(domainMap[sourceName] || [])];
        });
        return;
      }
      case 'Assign': {
        const targetColumns = normalizeStringArray(instruction.Target);
        if (!inputColumns.length || !targetColumns.length) return;
        const assigned = targetColumns.map((targetName, index) => ({
          targetName,
          sourceName: inputColumns[index] || inputColumns[inputColumns.length - 1]
        }));

        if (outputColumns.length) {
          assigned.forEach(({ sourceName }, index) => {
            const outputName = outputColumns[index] || outputColumns[outputColumns.length - 1];
            if (!outputName || !sourceName) return;
            domainMap[outputName] = [...(domainMap[sourceName] || [])];
          });
          return;
        }

        assigned.forEach(({ targetName, sourceName }) => {
          if (!targetName || !sourceName) return;
          domainMap[targetName] = [...(domainMap[sourceName] || [])];
        });
        return;
      }
      case 'DropNA': {
        if (!targetColumn) return;
        domainMap[targetColumn] = [...(domainMap[inputColumn] || [])];
        return;
      }
      case 'Split': {
        if (!inputColumns.length || !outputColumns.length) return;
        outputColumns.forEach((outputName) => {
          if (!outputName) return;
          domainMap[outputName] = [...(domainMap[inputColumn] || [])];
        });
        return;
      }
      case 'LabelIdenticalRows':
      case 'Label_identical_rows': {
        if (!inputColumns.length) return;
        if (outputColumns.length) {
          outputColumns.forEach((outputName) => { if (outputName) domainMap[outputName] = []; });
          return;
        }
        inputColumns.forEach((col) => { domainMap[`${col}_label`] = []; });
        return;
      }
      case 'MergeIdenticalRows':
        return;
      case 'Constant': {
        const outputName = outputColumns[0];
        if (!outputName) return;
        const rawValue = instruction.Value;
        domainMap[outputName] = [rawValue === undefined || rawValue === null || rawValue === '' ? '1' : String(rawValue)];
        return;
      }
      case 'Product':
      case 'Std':
      case 'Sum':
      case 'Scale':
      case 'Mean': {
        if (!targetColumn) return;
        domainMap[targetColumn] = [...(domainMap[inputColumn] || [])];
        return;
      }
      case 'Threshold': {
        if (!targetColumn) return;
        domainMap[targetColumn] = instruction.Binarize ? ['0', '1'] : [...(domainMap[inputColumn] || [])];
        return;
      }
      case 'Select': {
        if (!inputColumns.length) return;
        const keep = new Set(inputColumns);
        Object.keys(domainMap).forEach((name) => { if (!keep.has(name)) delete domainMap[name]; });
        return;
      }
      case 'Delete': {
        inputColumns.forEach((name) => { delete domainMap[name]; });
        return;
      }
      default:
        return;
    }
  }

  // Bare column name(s) this instruction introduces (before any "name.level" dot
  // expansion is layered on top by getModelXRegressors).
  function inferGeneratedColumns(domainMap, instruction) {
    if (!instruction || typeof instruction !== 'object') return [];

    const opName = String(instruction.Name || '').trim();
    const outputValues = normalizeStringArray(instruction.Output);

    if (opName === 'Factor') {
      const inputs = normalizeStringArray(instruction.Input);
      if (!inputs.length) return [];
      const levelSets = inputs.map((col) => domainMap[col] || []);
      if (levelSets.some((levels) => !levels.length)) {
        return inputs.map((col) => `${col}_*`);
      }
      const names = [];
      const build = (index, parts) => {
        if (index >= inputs.length) {
          names.push(parts.join('_'));
          return;
        }
        levelSets[index].forEach((level) => build(index + 1, [...parts, inputs[index], level]));
      };
      build(0, []);
      return names;
    }

    if (opName === 'LabelIdenticalRows' || opName === 'Label_identical_rows') {
      if (outputValues.length) return outputValues;
      return normalizeStringArray(instruction.Input).map((name) => `${name}_label`);
    }

    return outputValues;
  }

  function buildDomainMap(seedDomains, instructions) {
    const domainMap = {};
    Object.entries(seedDomains || {}).forEach(([name, values]) => {
      domainMap[name] = normalizeDomainValues(values);
    });
    (instructions || []).forEach((instruction) => applyDomainPropagation(domainMap, instruction));
    return domainMap;
  }

  // seedDomains: plain object of column name -> known string values (e.g.
  //   { trial_type: [...], condition: [...] }), used as the starting point before
  //   any instruction in the pipeline runs.
  // transformations: a node's Transformations object ({ Instructions, GeneratedColumns }).
  function getModelXRegressors(seedDomains, transformations) {
    const explicitGenerated = normalizeStringArray(transformations?.GeneratedColumns);
    const instructions = Array.isArray(transformations?.Instructions)
      ? transformations.Instructions.filter((item) => item && typeof item === 'object')
      : [];

    const domainMap = buildDomainMap(seedDomains, instructions);

    const inferredGenerated = Array.from(new Set(
      instructions.flatMap((instruction) => inferGeneratedColumns(domainMap, instruction))
    ));

    const dynamicGenerated = [];
    inferredGenerated.forEach((name) => {
      const domain = domainMap[name] || [];
      if (!shouldOfferLevelSuggestions(domain)) return;
      domain.forEach((level) => dynamicGenerated.push(`${name}.${level}`));
    });

    return Array.from(new Set([...explicitGenerated, ...inferredGenerated, ...dynamicGenerated])).filter((name) => {
      if (!name || name === '1') return false;
      if (name.startsWith('trial_type.') || name.startsWith('condition.')) return false;
      return true;
    });
  }

  window.TransformerModelXDomains = {
    buildDomainMap,
    inferGeneratedColumns,
    shouldOfferLevelSuggestions,
    getModelXRegressors
  };
})();
